def enable_dpi_awareness() -> bool:
    """Enable Per-Monitor V2 DPI awareness so coordinates and fonts scale properly across monitors."""
    # 1. Windows 10 1703+ (Per-Monitor V2 awareness)
    try:
        user32.SetProcessDpiAwarenessContext.argtypes = [ctypes.c_void_p]
        user32.SetProcessDpiAwarenessContext.restype = wintypes.BOOL
        # DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2 = -4
        if user32.SetProcessDpiAwarenessContext(ctypes.c_void_p(-4)):
            return True
    except Exception:
        pass

    # 2. Windows 8.1+ (Per-Monitor awareness)
    try:
        shcore = ctypes.WinDLL("shcore", use_last_error=True)
        shcore.SetProcessDpiAwareness.argtypes = [ctypes.c_int]
        shcore.SetProcessDpiAwareness.restype = ctypes.c_long
        # PROCESS_PER_MONITOR_DPI_AWARE = 2
        if shcore.SetProcessDpiAwareness(2) == 0:
            return True
    except Exception:
        pass

    # 3. Windows Vista+ fallback (System DPI aware)
    try:
        user32.SetProcessDPIAware.restype = wintypes.BOOL
        return bool(user32.SetProcessDPIAware())
    except Exception:
        return False


def is_windows_dark_mode() -> bool:
    """Return True if Windows system/apps theme is Dark, False if Light."""
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER,
            r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize",
        ) as key:
            val, _ = winreg.QueryValueEx(key, "AppsUseLightTheme")
            return val == 0
    except Exception:
        return True


def get_system_dpi() -> int:
    """Return primary display DPI (96 = 100%, 120 = 125%, 144 = 150%, etc.)."""
    try:
        LOGPIXELSX = 88
        hdc = user32.GetDC(None)
        if hdc:
            gdi32 = ctypes.WinDLL("gdi32", use_last_error=True)
            dpi = gdi32.GetDeviceCaps(hdc, LOGPIXELSX)
            user32.ReleaseDC(None, hdc)
            if dpi > 0:
                return int(dpi)
    except Exception:
        pass
    return 96


