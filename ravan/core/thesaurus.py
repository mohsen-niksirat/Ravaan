def lookup_synonyms(word: str) -> list[str]:
    """Return Persian synonyms and fluent equivalents for `word`."""
    w = normalize_arabic_chars(word or "").strip().replace("\u200c", "")
    if not w:
        return []

    results: list[str] = []
    for head, syns in _SYNONYM_GROUPS:
        head_norm = normalize_arabic_chars(head).replace("\u200c", "")
        syns_norm = [normalize_arabic_chars(s).replace("\u200c", "") for s in syns]
        if w == head_norm:
            for s in syns:
                if s not in results:
                    results.append(s)
        elif w in syns_norm:
            if head not in results:
                results.append(head)
            for s, s_n in zip(syns, syns_norm, strict=False):
                if s_n != w and s not in results:
                    results.append(s)
    return results


def check_homophones(text: str) -> list[HomophoneFix]:
    """Scan `text` for context-sensitive Persian homophone errors."""
    if not text:
        return []
    norm_text = normalize_arabic_chars(text)
    fixes: list[HomophoneFix] = []
    for wrong, (right, reason) in HOMOPHONE_CORRECTIONS.items():
        if wrong in norm_text:
            fixes.append(HomophoneFix(original=wrong, replacement=right, explanation=reason))
    return fixes


def apply_homophone_fixes(text: str) -> str:
    """Apply all context-certain homophone corrections to `text`."""
    if not text:
        return text
    out = normalize_arabic_chars(text)
    for wrong, (right, _reason) in HOMOPHONE_CORRECTIONS.items():
        if wrong in out:
            out = out.replace(wrong, right)
    return out


def check_trailing_homophone(recent_words: list[str]) -> HomophoneFix | None:
    """Check if the last 1–3 completed words match a known Persian homophone error."""
    if not recent_words:
        return None
    for n in (3, 2, 1):
        if len(recent_words) < n:
            continue
        span_raw = " ".join(recent_words[-n:])
        span_norm = normalize_arabic_chars(span_raw)
        hit = HOMOPHONE_CORRECTIONS.get(span_norm)
        if hit is not None:
            repl, reason = hit
            if repl != span_raw:
                return HomophoneFix(original=span_raw, replacement=repl, explanation=reason)
    return None


def strip_harakat(text: str) -> str:
    """Remove Persian/Arabic diacritics (harakat) and kashida (tatweel) while preserving ZWNJ."""
    if not text:
        return text
    return _HARAKAT_RE.sub("", text)


def lookup_harakat_variants(word: str) -> list[str]:
    """Return vowelized (harakat) disambiguation variants for a Persian homograph."""
    clean = strip_harakat(normalize_arabic_chars(word or "").strip())
    return list(_COMMON_HARAKAT.get(clean, ()))
